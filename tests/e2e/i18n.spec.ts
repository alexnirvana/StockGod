import { test, expect } from '../../frontend/e2e/fixtures'

test('English onboarding, aligned experiment comparison and saved account language', async ({ page }) => {
  const username = 'locale_' + Date.now()
  const password = 'isolated-locale-test-2026'
  await page.goto('/login')
  await page.getByRole('combobox').selectOption('en')
  await page.getByRole('tab', { name: 'Register', exact: true }).click()
  await page.getByRole('textbox', { name: 'Username', exact: true }).fill(username)
  await page.getByRole('textbox', { name: 'Password Show password', exact: true }).fill(password)
  await page.getByRole('textbox', { name: 'Confirm password', exact: true }).fill(password)
  await page.getByRole('button', { name: 'Register and start learning', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Welcome to your learning space')
  await page.getByRole('button', { name: 'Skip tour', exact: true }).click()
  await page.getByRole('link', { name: 'Practice', exact: true }).click()
  await page.getByRole('spinbutton', { name: 'Limit price', exact: true }).fill('22.00')
  await page.getByRole('combobox', { name: 'Language', exact: true }).selectOption('zh-CN')
  await expect(page.getByRole('spinbutton', { name: '委托价格', exact: true })).toHaveValue('22.00')
  await page.getByRole('combobox', { name: '界面语言', exact: true }).selectOption('en')
  await expect(page.getByRole('spinbutton', { name: 'Limit price', exact: true })).toHaveValue('22.00')
  await page.getByRole('link', { name: 'Strategy Lab', exact: true }).click()
  for (const window of [10, 20]) {
    await page.getByRole('spinbutton', { name: 'Long window (teaching days)', exact: true }).fill(String(window))
    await page.getByRole('button', { name: 'Run teaching backtest', exact: true }).click()
    await expect(page.getByText('Completed', { exact: true })).toBeVisible({ timeout: 20000 })
  }
  await page.getByRole('button', { name: 'Compare runs', exact: true }).click()
  await page.getByRole('checkbox', { name: /MA 5\/10/ }).check()
  await page.getByRole('checkbox', { name: /MA 5\/20/ }).check()
  await page.getByRole('button', { name: 'Compare selected runs', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Common period: teaching days 21–60')
  await expect(page.getByRole('columnheader', { name: 'Full-run fees' })).toBeVisible()
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('combobox', { name: 'Language', exact: true }).selectOption('zh-CN')
  await expect(page.getByRole('link', { name: '策略实验', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '账号菜单', exact: true }).click()
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.getByRole('combobox').selectOption('en')
  await page.getByRole('textbox', { name: 'Username', exact: true }).fill(username)
  await page.getByRole('textbox', { name: 'Password Show password', exact: true }).fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('combobox', { name: '界面语言', exact: true })).toHaveValue('zh-CN')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
